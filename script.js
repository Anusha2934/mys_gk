/* =====================================================
   GAME VARIABLES
   ===================================================== */

let currentQuestion = 0;
let answered = false;

const completedLevels = new Set();

const screens = {
    home: document.getElementById("screen-home"),
    levels: document.getElementById("screen-levels"),
    quiz: document.getElementById("screen-quiz")
};


/* =====================================================
   SCREEN NAVIGATION
   ===================================================== */

function showScreen(screenName) {

    Object.values(screens).forEach(screen => {
        screen.classList.remove("active");
    });

    screens[screenName].classList.add("active");
}


/* =====================================================
   QUESTION SELECTION
   ===================================================== */

const levelGrid = document.getElementById("level-grid");

function renderLevels() {

    levelGrid.innerHTML = "";

    questions.forEach((question, index) => {

        const button = document.createElement("button");

        button.className = "level-btn";
        button.textContent = index + 1;

        if (completedLevels.has(index)) {
            button.classList.add("completed");
        }

        button.addEventListener("click", () => {

            currentQuestion = index;

            showQuestion();

            showScreen("quiz");

        });

        levelGrid.appendChild(button);

    });

}


/* =====================================================
   DISPLAY QUESTION
   ===================================================== */

function showQuestion() {

    answered = false;

    const question = questions[currentQuestion];

    const questionText = document.getElementById("question-text");
    const optionsGrid = document.getElementById("options-grid");

    questionText.textContent = question.q;

    optionsGrid.innerHTML = "";

    // Apply a smaller font specifically to Question 16
    const quizScreen = document.getElementById("screen-quiz");

    quizScreen.classList.toggle(
        "question-16",
        currentQuestion === 15
    );

    question.options.forEach((option, index) => {

        const button = document.createElement("button");

        button.className = "option-btn";
        button.textContent = option;

        button.addEventListener("click", () => {
            checkAnswer(index);
        });

        optionsGrid.appendChild(button);

    });

}


/* =====================================================
   INSTANT ANSWER CHECKING
   ===================================================== */

function checkAnswer(selectedIndex) {

    // Prevent selecting multiple answers
    if (answered) return;

    answered = true;

    const question = questions[currentQuestion];

    const correctIndex = question.answer;

    const optionButtons = document.querySelectorAll(".option-btn");

    // Disable all options after selection
    optionButtons.forEach(button => {
        button.disabled = true;
    });

    // Correct answer turns green
    optionButtons[correctIndex].classList.add("correct");

    // Wrong selected answer turns red
    if (selectedIndex !== correctIndex) {
        optionButtons[selectedIndex].classList.add("wrong");
    }

    // Mark question as completed
    completedLevels.add(currentQuestion);

    // Update question selection screen
    renderLevels();

}


/* =====================================================
   BUTTON EVENT LISTENERS
   ===================================================== */

document.getElementById("btn-start").addEventListener("click", () => {

    renderLevels();

    showScreen("levels");

});


document.getElementById("btn-back-to-home").addEventListener("click", () => {

    showScreen("home");

});


document.getElementById("btn-back-to-levels").addEventListener("click", () => {

    renderLevels();

    showScreen("levels");

});


document.getElementById("btn-home-from-quiz").addEventListener("click", () => {

    renderLevels();

    showScreen("levels");

});


/* =====================================================
   INITIALIZE APPLICATION
   ===================================================== */

renderLevels();

showScreen("home");